"""Build UARTRS232.dll and refresh the copy the app carries.

    python extra/UARTRS232/build_plugin.py [--plugin-dll PATH] [--compiler PATH]

Two outputs, always written together:

* ``extra/UARTRS232/UARTRS232.dll`` - the plugin itself, for anyone who
  wants to drop it into a CSpect folder by hand;
* ``zxnu_cspect_esp_blob.py`` (repo root) - the same bytes as a Python
  module, which is how the app ships it: a module rides in the wheel, the
  PyInstaller executables and the Flatpak with no packaging rule of its own.

The compiler is the C# 5 ``csc.exe`` that every Windows carries with the
.NET Framework (no SDK, no NuGet), or mono's ``mcs`` elsewhere. It needs
CSpect's own ``Plugin.dll`` to compile against - the interface assembly that
ships in every CSpect folder; by default the newest one under
``downloads/itchio`` is used. That file is CSpect's and is NOT copied into
this repository: at run time the plugin binds to whichever Plugin.dll the
CSpect loading it carries.

The in-box compiler is not deterministic (every build stamps a fresh module
id), so rebuild only when UARTRS232.cs changed - and bump its
``PluginVersion`` when it did. ``tests/test_cspect_esp_plugin.py`` fails when
the source and the shipped binary drift apart: the blob records a digest of
the source it was built from.
"""
import argparse
import base64
import glob
import hashlib
import os
import re
import shutil
import subprocess
import sys
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)

from zxnu_cspect_esp import (  # noqa: E402
    CSPECT_ESP_PLUGIN_FILE, plugin_banner, plugin_source_digest,
    plugin_source_version)

SOURCE = os.path.join(HERE, "UARTRS232.cs")
OUTPUT = os.path.join(HERE, CSPECT_ESP_PLUGIN_FILE)
BLOB = os.path.join(ROOT, "zxnu_cspect_esp_blob.py")


def find_compiler():
    """The C# compiler to use: (path, kind)."""
    windir = os.environ.get("WINDIR") or os.environ.get("SystemRoot")
    if windir:
        for arch in ("Framework64", "Framework"):
            csc = os.path.join(windir, "Microsoft.NET", arch,
                               "v4.0.30319", "csc.exe")
            if os.path.isfile(csc):
                return csc
    for name in ("mcs", "csc"):
        found = shutil.which(name)
        if found:
            return found
    return None


def _folder_version(path):
    digits = re.findall(r"\d+", os.path.basename(os.path.dirname(path)))
    return tuple(int(d) for d in digits)


def find_plugin_dll():
    """CSpect's interface assembly: the newest copy under downloads/."""
    found = glob.glob(os.path.join(ROOT, "downloads", "itchio", "**",
                                   "Plugin.dll"), recursive=True)
    return max(found, key=_folder_version) if found else None


def write_blob(dll_bytes, version, source_digest):
    encoded = base64.b64encode(dll_bytes).decode("ascii")
    body = "\n".join(textwrap.wrap(encoded, 76))
    text = (
        '"""The CSpect ESP plugin (UARTRS232.dll) as the app carries it.\n'
        "\n"
        "GENERATED by extra/UARTRS232/build_plugin.py from\n"
        "extra/UARTRS232/UARTRS232.cs - do not edit by hand. Read through\n"
        "zxnu_cspect_esp (plugin_bytes / deploy_plugin), never directly.\n"
        '"""\n'
        "\n"
        f'PLUGIN_VERSION = "{version}"\n'
        f"PLUGIN_SIZE = {len(dll_bytes)}\n"
        f'PLUGIN_SHA256 = "{hashlib.sha256(dll_bytes).hexdigest()}"\n'
        f'SOURCE_SHA256 = "{source_digest}"\n'
        'PLUGIN_BASE64 = """\n'
        f"{body}\n"
        '"""\n')
    with open(BLOB, "w", encoding="ascii", newline="\n") as handle:
        handle.write(text)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--plugin-dll", default=None,
                        help="CSpect's Plugin.dll to compile against "
                             "(default: the newest under downloads/itchio)")
    parser.add_argument("--compiler", default=None,
                        help="csc.exe or mcs (default: the .NET Framework "
                             "csc.exe, else mcs on PATH)")
    args = parser.parse_args(argv)

    compiler = args.compiler or find_compiler()
    if not compiler:
        print("No C# compiler found: install the .NET Framework (Windows) "
              "or mono (mcs), or pass --compiler.", file=sys.stderr)
        return 2
    plugin_dll = args.plugin_dll or find_plugin_dll()
    if not plugin_dll or not os.path.isfile(plugin_dll):
        print("CSpect's Plugin.dll was not found: install CSpect from the "
              "itch.io tab, or pass --plugin-dll <CSpect folder>/Plugin.dll.",
              file=sys.stderr)
        return 2

    version = plugin_source_version(SOURCE)
    if not version:
        print("PluginVersion was not found in " + SOURCE, file=sys.stderr)
        return 2

    command = [compiler, "-nologo", "-target:library", "-optimize+",
               "-debug-", "-warnaserror+", "-out:" + OUTPUT,
               "-reference:" + plugin_dll, SOURCE]
    print("compiler :", compiler)
    print("interface:", plugin_dll)
    done = subprocess.run(command, capture_output=True, text=True)
    sys.stdout.write(done.stdout)
    sys.stderr.write(done.stderr)
    if done.returncode != 0:
        print("build failed", file=sys.stderr)
        return done.returncode

    with open(OUTPUT, "rb") as handle:
        dll_bytes = handle.read()
    if plugin_banner(version) not in dll_bytes:
        print("the built DLL does not carry the banner for version "
              + version, file=sys.stderr)
        return 1
    write_blob(dll_bytes, version, plugin_source_digest([SOURCE]))
    print(f"built    : {OUTPUT} ({len(dll_bytes)} bytes, version {version})")
    print(f"refreshed: {BLOB}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
